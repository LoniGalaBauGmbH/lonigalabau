// Regenerate with: node scripts/generate-customer-email-assets.mjs <absolute-path-to-sharp>
import fs from "node:fs/promises";
import { createRequire } from "node:module";
const sharp = createRequire(import.meta.url)(process.argv[2] || "sharp");
const root = new URL("../", import.meta.url);
const photos = {};
for (const [kind, file, position] of [
  ["contact", "rasengarten-mit-plattenterrasse.webp", "south"],
  ["application", "loni-team-baustelle.webp", "centre"],
]) {
  const bytes = await sharp(await fs.readFile(new URL("public/images/projekte/" + file, root)))
    .resize(1280, 600, { fit: "cover", position })
    .jpeg({ quality: 82, mozjpeg: true })
    .toBuffer();
  photos[kind] = {
    filename: `loni-${kind}.jpg`,
    content: bytes.toString("base64"),
    content_type: "image/jpeg",
    content_id: "confirmation-photo-v1",
  };
  console.log(kind + ": " + bytes.length + " bytes");
}
await fs.writeFile(
  new URL("src/lib/customer-email-assets.server.ts", root),
  "// Generated by scripts/generate-customer-email-assets.mjs from approved website photos.\nexport const CUSTOMER_EMAIL_PHOTOS = " +
    JSON.stringify(photos, null, 2) +
    ";\n",
);
