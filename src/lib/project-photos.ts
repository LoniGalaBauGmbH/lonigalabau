const byName = new Map(
  Object.values(projectPhotos).map((photo) => [photo.src.split("/").pop(), photo]),
);
function metadata(src: string) {
  if (!src.includes("/images/projekte/") && !src.includes("/project-images/referenzen-2026/"))
    return;
  return byName.get(src.split("/").pop());
}
export function photoSrcSet(src: string) {
  const photo = metadata(src);
  return photo
    ? `${src.replace(/\.webp$/, "-small.webp")} ${photo.smallWidth}w, ${src} ${photo.width}w`
    : undefined;
}
export function photoAlt(src: string, fallback: string) {
  return fallback === "" ? "" : (metadata(src)?.alt ?? fallback);
}
